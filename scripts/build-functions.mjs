// Bundles each Edge Function into one self-contained file under supabase/functions/<name>/index.ts.
// Their code lives in src/server and reuses the app's own rules (src/domain), so the server and the app
// always agree on what "today", "slipping" and "overdue" mean. Run after changing either:
//   npm run build:functions
// Tests (src/server/*/bundle.test.ts) fail if a committed file is out of date.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { rolldown } from 'rolldown';

const root = fileURLToPath(new URL('..', import.meta.url));

export const FUNCTIONS = {
  notify: {
    entry: 'src/server/notify/entry.deno.ts',
    about: 'The Four Burners notify Edge Function: sends daily, weekly and smart-nudge Web Push notifications.',
    from: 'src/server/notify',
  },
  shortcuts: {
    entry: 'src/server/shortcuts/entry.deno.ts',
    about: 'The Four Burners shortcuts Edge Function: Siri and Apple Shortcuts logging, and Apple Health data.',
    from: 'src/server/shortcuts',
  },
};

/** Where a function's bundle is committed. */
export const outputOf = (name) => `${root}supabase/functions/${name}/index.ts`;
export const OUTPUT = outputOf('notify');

/** The bundled source of one function. */
export async function bundleFunction(name) {
  const fn = FUNCTIONS[name];
  const bundle = await rolldown({
    input: `${root}${fn.entry}`,
    platform: 'neutral',
    resolve: { alias: { '@': `${root}src` } },
    logLevel: 'warn',
  });
  try {
    const { output } = await bundle.generate({ format: 'esm', comments: { legal: false, annotation: false, jsdoc: false } });
    const header = `// @ts-nocheck
// GENERATED by \`npm run build:functions\` from ${fn.from} and src/domain. Do not edit by hand.
// ${fn.about}
// Deploy: README.
`;
    return header + output[0].code.replace(/\r\n/g, '\n');
  } finally {
    await bundle.close();
  }
}

export const bundleNotify = () => bundleFunction('notify');

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { mkdirSync } = await import('node:fs');
  for (const name of Object.keys(FUNCTIONS)) {
    mkdirSync(`${root}supabase/functions/${name}`, { recursive: true });
    writeFileSync(outputOf(name), await bundleFunction(name));
    console.log(`Wrote ${outputOf(name)}`);
  }
}
