// Bundles the notify Edge Function into one self-contained file: supabase/functions/notify/index.ts.
// The function's code lives in src/server/notify and reuses the app's own rules (src/domain), so the server
// and the app always agree on what "today", "slipping" and "overdue" mean. Run after changing either:
//   npm run build:functions
// A test (src/server/notify/bundle.test.ts) fails if the committed file is out of date.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { rolldown } from 'rolldown';

const root = fileURLToPath(new URL('..', import.meta.url));
export const OUTPUT = `${root}supabase/functions/notify/index.ts`;

const HEADER = `// @ts-nocheck
// GENERATED by \`npm run build:functions\` from src/server/notify and src/domain. Do not edit by hand.
// The Four Burners notify Edge Function: sends daily, weekly and smart-nudge Web Push notifications.
// Deploy: README > Notifications.
`;

/** The bundled function source. */
export async function bundleNotify() {
  const bundle = await rolldown({
    input: `${root}src/server/notify/entry.deno.ts`,
    platform: 'neutral',
    resolve: { alias: { '@': `${root}src` } },
    logLevel: 'warn',
  });
  try {
    const { output } = await bundle.generate({ format: 'esm', comments: { legal: false, annotation: false, jsdoc: false } });
    return HEADER + output[0].code.replace(/\r\n/g, '\n');
  } finally {
    await bundle.close();
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(OUTPUT, await bundleNotify());
  console.log(`Wrote ${OUTPUT}`);
}
